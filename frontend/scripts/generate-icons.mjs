import sharp from 'sharp';
import { writeFileSync, existsSync, unlinkSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

/**
 * Every Omega icon is drawn from the artwork below: a calendar page with an
 * amber header and an omega on it, on an indigo tile. It's laid out on
 * Android's 108dp adaptive icon grid, where launchers show the central 72dp
 * and, whatever shape they mask it to, keep the central 66dp circle.
 * - The tile is src/assets/omega-mark.svg (<Logo variant="mark" />), the
 *   favicon, the PWA and desktop icons, and Android's pre-8.0 launcher icon.
 * - Android 8+ gets the page as a layer over the indigo, plus a one-tone
 *   layer for themed icons (Android 13+) and the notification icon.
 */
const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const assetsDir = join(__dirname, '..', 'src', 'assets');
const publicDir = join(__dirname, '..', 'public');
const srcTauriDir = join(__dirname, '..', 'src-tauri');

const INDIGO = '#4f46e5';
const AMBER = '#f59e0b';

const HEADER = 'M31 44a8 8 0 0 1 8-8h30a8 8 0 0 1 8 8v3H31z';
const SHEET = 'M31 47H77V70a8 8 0 0 1-8 8H39a8 8 0 0 1-8-8z';
const RINGS =
  '<rect x="40.5" y="30" width="5" height="11" rx="2.5"/>' +
  '<rect x="62.5" y="30" width="5" height="11" rx="2.5"/>';
const OMEGA = 'M44.5 71.5H49.12V67.96A8.5 8.5 0 1 1 58.88 67.96V71.5H63.5';
const omegaStroke = (color) =>
  `<path d="${OMEGA}" fill="none" stroke="${color}" stroke-width="4.5" ` +
  'stroke-linecap="round" stroke-linejoin="round"/>';

/** In color: a white page, its header amber, the omega in the tile's indigo. */
const page = `
  <path d="${HEADER}" fill="${AMBER}"/>
  <path d="${SHEET}" fill="#ffffff"/>
  <g fill="#ffffff">${RINGS}</g>
  ${omegaStroke(INDIGO)}`;

/**
 * In one tone: the page solid, with the line under the header and the omega
 * cut out of it. Android draws only the alpha of themed and notification
 * icons, so this is white on transparent.
 */
const silhouette = `
  <mask id="cut">
    <rect width="108" height="108" fill="#ffffff"/>
    <path d="M31 47H77" stroke="#000000" stroke-width="2.5"/>
    ${omegaStroke('#000000')}
  </mask>
  <g mask="url(#cut)" fill="#ffffff">
    <path d="${HEADER}"/>
    <path d="${SHEET}"/>
    ${RINGS}
  </g>`;

const tile = (radius) =>
  `<rect x="18" y="18" width="72" height="72" rx="${radius}" fill="${INDIGO}"/>${page}`;

const art = {
  /** The visible 72dp, rounded like a launcher would. */
  tile: { viewBox: '18 18 72 72', body: tile(16) },
  /** Full bleed, for icons the platform rounds itself (iOS, legacy Android). */
  squareTile: { viewBox: '18 18 72 72', body: tile(0) },
  foreground: { viewBox: '0 0 108 108', body: page },
  monochrome: { viewBox: '0 0 108 108', body: silhouette },
  /** Cropped so the page fills the status bar's 24dp, less its 2dp margin. */
  notification: { viewBox: '25 25 58 58', body: silhouette },
};

// Sized in the SVG itself: sharp rasterizes at the SVG's own size, so
// resizing afterwards would blur it.
const svg = ({ viewBox, body }, size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${size}" height="${size}">` +
  `${body}</svg>\n`;
const render = (artwork, size, file) => sharp(Buffer.from(svg(artwork, size))).png().toFile(file);

writeFileSync(
  join(assetsDir, 'omega-mark.svg'),
  `<!-- Generated by scripts/generate-icons.mjs (npm run icons); edit the artwork there. -->\n` +
    svg(art.tile, 72)
);
console.log('Generated src/assets/omega-mark.svg');

const outputs = [
  { name: 'favicon-32.png', size: 32, artwork: art.tile },
  // iOS rounds the icon itself, and shows transparency as black.
  { name: 'apple-touch-icon.png', size: 180, artwork: art.squareTile },
  { name: 'icon-192.png', size: 192, artwork: art.tile },
  { name: 'icon-512.png', size: 512, artwork: art.tile },
];
for (const { name, size, artwork } of outputs) {
  await render(artwork, size, join(publicDir, name));
  console.log(`Generated ${name} (${size}x${size})`);
}

/**
 * Sources for the Tauri desktop and Android app icons. `npm run icons` hands
 * app-icon.json to `tauri icon`, which cuts every size and density from the
 * images, writes the adaptive icon with its foreground, indigo background
 * and monochrome layers, and uses app-icon.png for desktop and pre-8.0
 * Android.
 */
const tauriIconSize = 1024;
await render(art.squareTile, tauriIconSize, join(srcTauriDir, 'app-icon.png'));
await render(art.foreground, tauriIconSize, join(srcTauriDir, 'app-icon-foreground.png'));
await render(art.monochrome, tauriIconSize, join(srcTauriDir, 'app-icon-monochrome.png'));
writeFileSync(
  join(srcTauriDir, 'app-icon.json'),
  JSON.stringify(
    {
      default: 'app-icon.png',
      bg_color: INDIGO,
      android_fg: 'app-icon-foreground.png',
      // The layers are drawn on the full 108dp grid already.
      android_fg_scale: 100,
      android_monochrome: 'app-icon-monochrome.png',
    },
    null,
    2
  ) + '\n'
);
console.log(`Generated src-tauri/app-icon*.png (${tauriIconSize}x${tauriIconSize}), app-icon.json`);

/**
 * Status bar icon for reminder notifications (src/tauri/reminder-device.ts),
 * 24dp at each density. `tauri icon` leaves drawable-* alone.
 */
const androidResDir = join(srcTauriDir, 'gen', 'android', 'app', 'src', 'main', 'res');
const statusIconSizes = { mdpi: 24, hdpi: 36, xhdpi: 48, xxhdpi: 72, xxxhdpi: 96 };
for (const [density, size] of Object.entries(statusIconSizes)) {
  const dir = join(androidResDir, `drawable-${density}`);
  mkdirSync(dir, { recursive: true });
  await render(art.notification, size, join(dir, 'ic_stat_omega.png'));
  console.log(`Generated android drawable-${density}/ic_stat_omega.png (${size}x${size})`);
}

const legacySvg = join(publicDir, 'omega-icon.svg');
if (existsSync(legacySvg)) {
  unlinkSync(legacySvg);
  console.log('Removed legacy public/omega-icon.svg');
}

const legacyGeneratedMark = join(assetsDir, 'omega-app-icon.png');
if (existsSync(legacyGeneratedMark)) {
  unlinkSync(legacyGeneratedMark);
  console.log('Removed legacy src/assets/omega-app-icon.png (mark is SVG now)');
}

console.log('All icons generated successfully!');
